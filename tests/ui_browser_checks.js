"use strict";
(async () => {
  const checks = [];
  const assert = (condition, label) => { if (!condition) throw Error(label); checks.push(label); };
  const form = document.getElementById("question-form"), field = document.getElementById("question"), button = document.getElementById("submit"), notice = document.getElementById("notice"), result = document.getElementById("result");
  const clarification = document.getElementById("clarification"), yearField = document.getElementById("clarification-year-field"), yearInput = document.getElementById("clarification-year"), metricField = document.getElementById("clarification-metric-field"), complete = document.getElementById("clarification-complete"), metrics = [...document.querySelectorAll('input[name="clarification-metric"]')];
  const originalFetch = window.fetch;
  const requests = [];
  window.fetch = (url, options) => { requests.push({url, body: JSON.parse(options.body)}); return originalFetch(url, options); };
  async function send(question) {
    field.value = question;
    form.dispatchEvent(new Event("submit", {cancelable: true}));
    assert(button.disabled && form.getAttribute("aria-busy") === "true", "waiting disables resubmission");
    form.dispatchEvent(new Event("submit", {cancelable: true}));
    await new Promise((resolve, reject) => {
      const timeout = setTimeout(() => reject(Error("UI response timeout")), 10000);
      const observer = new MutationObserver(() => {
        if (!button.disabled) { observer.disconnect(); clearTimeout(timeout); resolve(); }
      });
      observer.observe(form, {attributes: true, subtree: true});
    });
    assert(form.getAttribute("aria-busy") === "false", "controls recover");
  }
  try {
    assert(notice.dataset.state === "idle" && result.hidden, "initial page has no request or result");
    const examples = [...document.querySelectorAll("[data-example]")];
    assert(examples.length === 3, "all three fixed examples are shown");
    examples.forEach(example => {
      example.click();
      assert(field.value === example.dataset.example, "example fills only the question field");
      assert(requests.length === 0, "example never submits a request");
    });
    assert(field.value === "2023 ve 2024 TÜFE değişimlerini karşılaştır.", "comparison example fills its exact question");
    assert(document.body.textContent.includes("TÜFE karşılaştırması · 2023 / 2024"), "comparison example is labelled");
    await send("2021 Ocak-Şubat faiz düşerken reel konut kredisi stokunun artmadığı ayları göster.");
    assert(notice.dataset.state === "ok" && !result.hidden, "physical package housing succeeds");
    assert(result.querySelector(".js-plotly-plot")?.data.length === 6, "existing six-trace Plotly chart rendered");
    assert(result.textContent.includes("koşula uyan ay bulunamadı"), "empty match state");
    assert(result.textContent.includes("2025 fiyatları") && result.textContent.includes("unverified"), "units and quality visible");
    await send("2021 Ocak-Şubat TÜFE değişimleri");
    assert(notice.dataset.state === "ok" && result.querySelectorAll("tbody tr").length === 2, "CPI table uses actual API rows");
    assert(result.querySelector("tbody").textContent.includes("—"), "missing CPI history is not zero");
    const cpiPlot = result.querySelector(".js-plotly-plot");
    assert(cpiPlot?.data.length === 3 && result.querySelectorAll(".js-plotly-plot").length === 1, "CPI renders three panels and replaces the housing chart");
    assert(cpiPlot.data.map(trace => trace.name).join("|") === "TÜFE endeksi (2025=100)|Aylık değişim (%)|Yıllık değişim (%)", "CPI panel titles are preserved");
    const cpiPeriods = [...result.querySelectorAll("tbody tr td:first-child")].map(cell => cell.textContent);
    assert(JSON.stringify(cpiPlot.data[0].x.map(value => value.slice(0, 7))) === JSON.stringify(cpiPeriods), "CPI chart and table use the same evidence months");
    assert(result.textContent.includes("TÜFE makbuz"), "CPI sources remain visible");
    await send('<img src=x onerror="window.UI_XSS=true">');
    assert(notice.dataset.state === "clarification_required" && result.hidden, "clarification hides stale result");
    assert(!result.querySelector(".js-plotly-plot"), "clarification purges the previous CPI chart");
    assert(!window.UI_XSS && field.value.startsWith("<img"), "user text never executes");
    await send("unsupported");
    assert(notice.dataset.state === "unsupported", "unsupported decision shown");
    await send("provider");
    assert(notice.dataset.state === "error" && !document.body.textContent.includes("PRIVATE-PROVIDER-RESPONSE"), "provider body remains private");
    await send("Ocak-Şubat TÜFE değişimlerini özetle.");
    assert(notice.dataset.state === "clarification_required" && !clarification.hidden && !yearField.hidden && metricField.hidden, "missing year offers a short year completion");
    assert(complete.disabled === false, "year completion is available");
    const beforeYear = requests.length;
    yearInput.value = "2021";
    complete.click();
    assert(requests.length === beforeYear, "completing the missing year makes no request");
    assert(field.value === "2021 Ocak-Şubat TÜFE değişimlerini özetle.", "year is inserted while preserving the narrow month range");
    assert(clarification.hidden && notice.dataset.state === "clarified", "completed question stays editable and is not submitted");
    await send(field.value);
    assert(notice.dataset.state === "ok" && result.querySelectorAll("tbody tr").length === 2, "completed year runs the correct CPI period");
    await send("ikinci çeyrek TÜFE değişimlerini özetle.");
    assert(!yearField.hidden, "missing quarter year offers completion");
    const beforeQuarter = requests.length;
    yearInput.value = "2021";
    complete.click();
    assert(requests.length === beforeQuarter && field.value === "2021 yılının ikinci çeyrek TÜFE değişimlerini özetle.", "quarter period is preserved when adding the year");
    await send("2021 ve 2022 Ocak-Şubat TÜFE değişimlerini özetle.");
    assert(notice.dataset.state === "clarification_required" && yearField.hidden && complete.disabled, "existing conflicting dates are not offered a year rewrite");
    const conflictText = field.value, beforeConflict = requests.length;
    complete.click();
    assert(field.value === conflictText && requests.length === beforeConflict && result.hidden, "conflicting completion never rewrites the question or runs an analysis");
    await send("2021 Ocak-Şubat faiz düşerken kredi bakiyesinin artmadığı ayları göster.");
    assert(!metricField.hidden && yearField.hidden, "ambiguous credit metric offers Reel/Nominal");
    const beforeReel = requests.length;
    metrics.find(input => input.value === "reel").checked = true;
    complete.click();
    assert(requests.length === beforeReel, "metric completion makes no request");
    assert(field.value.includes("reel kredi bakiyesinin"), "Reel is applied to the credit balance expression");
    await send(field.value);
    assert(notice.dataset.state === "ok" && !result.hidden, "Reel selection passes the existing guard");
    await send("2021 Ocak-Şubat faiz düşerken kredi stoku artmayan ayları göster.");
    assert(!metricField.hidden, "ambiguous filter metric offers Reel/Nominal");
    const beforeNominal = requests.length;
    metrics.find(input => input.value === "nominal").checked = true;
    complete.click();
    assert(requests.length === beforeNominal, "nominal completion makes no request");
    assert(field.value.includes("nominal kredi stoku artmayan"), "Nominal is applied to the credit stock expression");
    await send(field.value);
    assert(notice.dataset.state === "ok" && result.textContent.includes("Koşullar (AND)"), "Nominal selection passes the filter guard");
    await send("Ocak-Şubat TÜFE değişimlerini özetle.");
    assert(!clarification.hidden, "clarification is shown again for a fresh question");
    field.value = "2021 Ocak-Şubat TÜFE değişimlerini özetle.";
    field.dispatchEvent(new Event("input"));
    assert(clarification.hidden, "manual editing discards stale clarification context");
    const beforeStale = requests.length;
    complete.click();
    assert(field.value === "2021 Ocak-Şubat TÜFE değişimlerini özetle." && requests.length === beforeStale, "stale completion cannot rewrite an edited question");
    await send("Ocak-Şubat TÜFE değişimlerini özetle.");
    assert(!clarification.hidden, "clarification can be reopened");
    examples[2].click();
    assert(clarification.hidden && field.value === "2023 ve 2024 TÜFE değişimlerini karşılaştır.", "example selection discards stale clarification context");
    assert(requests.length === 15 && requests.every(r => r.url === "/analysis/economic/question/files" && Object.keys(r.body).join() === "question"), "one request each with only question");
    window.fetch = async () => new Response(JSON.stringify({detail: {code: "economic_data_unavailable", message: "PRIVATE-PATH"}}), {status: 503, headers: {"Content-Type": "application/json"}});
    await send("missing data");
    assert(notice.textContent.includes("veri paketi") && !document.body.textContent.includes("PRIVATE-PATH"), "safe missing-data state");
    window.fetch = async () => { throw Error("PRIVATE-NETWORK"); };
    await send("network");
    assert(notice.dataset.state === "error" && !document.body.textContent.includes("PRIVATE-NETWORK"), "network recovery state");
    const matched = __MATCHED_PAYLOAD__;
    matched.analysis.evidence.bddk_source_refs = ['<img src=x onerror="window.UI_XSS=true">'];
    window.fetch = async () => new Response(JSON.stringify(matched), {headers: {"Content-Type": "application/json"}});
    await send("matched response");
    assert(result.querySelectorAll("tbody tr").length === 1 && result.querySelector("tbody tr td").textContent === "2021-02", "match table displays calculated evidence row");
    assert(result.textContent.includes("3 ayın 1 tanesinde"), "summary reads evidence counters");
    assert(!result.querySelector("img") && !window.UI_XSS && result.textContent.includes("<img src=x"), "source text is inert text, not HTML");
    const filter = __FILTER_PAYLOAD__;
    window.fetch = async () => new Response(JSON.stringify(filter), {headers: {"Content-Type": "application/json"}});
    await send("filter response");
    assert(result.textContent.includes("Koşullar (AND)") && result.textContent.includes("Nominal konut kredisi değişimi"), "filter conditions are summarized");
    assert(result.textContent.includes("değerlendirilebildi") && result.textContent.includes("Eşleşen aylar (1)"), "filter counters use evidence");
    assert(result.querySelectorAll("tbody tr").length === 3 && result.textContent.includes("2021-02"), "filter condition and match tables render");
    assert(!result.querySelector(".chart") && !result.querySelector(".js-plotly-plot"), "filter never reuses the legacy housing chart");
    const comparison = __COMPARISON_PAYLOAD__;
    window.fetch = async () => new Response(JSON.stringify(comparison), {headers: {"Content-Type": "application/json"}});
    await send("comparison response");
    assert(result.querySelectorAll("tbody tr").length === 24, "both full-year CPI tables render");
    assert(result.textContent.includes("2023 · Ocak–Aralık") && result.textContent.includes("2024 · Ocak–Aralık"), "each compared year is labelled");
    const indexChanges = [...result.querySelectorAll(".comparison-index-change")];
    assert(indexChanges.length === 2, "both full-year index changes render separately");
    assert(indexChanges[0].textContent.includes("2023 Ocak–Aralık endeks değişimi: %17,6471"), "2023 index change uses percent under its own year");
    assert(indexChanges[1].textContent.includes("2024 Ocak–Aralık endeks değişimi: %21,9512"), "2024 index change uses percent under its own year");
    assert(indexChanges.every(node => node.textContent.includes("Aralık yıllık TÜFE oranı veya yüzde puan farkı değildir")), "index changes are labelled apart from annual rates and percentage-point difference");
    assert(result.textContent.includes("+5 yüzde puan"), "comparison difference uses percentage points");
    assert(result.textContent.includes("null kalır"), "missing-value behavior is explained");
    assert(result.textContent.includes("TÜFE makbuz"), "comparison sources remain visible");
    assert(!result.querySelector(".chart"), "comparison removes the previous CPI chart");
    const marker = document.createElement("pre"); marker.id = "ui-test-result"; marker.textContent = JSON.stringify({ok: true, checks: checks.length}); document.body.append(marker);
  } catch (error) {
    const marker = document.createElement("pre"); marker.id = "ui-test-result"; marker.textContent = JSON.stringify({ok: false, checks, error: String(error)}); document.body.append(marker);
  }
})();
